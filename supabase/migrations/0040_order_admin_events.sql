-- ============================================================
-- SORA LIFE — 0040 ORDER ADMIN EVENTS: who did what to an order
-- Run once in the Supabase SQL Editor ("sora life"), BEFORE the code that
-- calls mark_cod_collected() is pushed. Safe to re-run.
--
-- "Mark cash collected" (the admin Orders page, /api/admin/mark-cod-collected)
-- turns a cash-on-delivery order into a paid one and issues its invoice
-- number — and recorded nothing about who pressed it. This adds:
--
--   order_admin_events   one row per admin action on an order: which order,
--                        what, which admin (their user id, and their email as
--                        it was at the time), when. Starts with one action,
--                        'cod_collected'; later admin actions can join it.
--   mark_cod_collected() marks the order paid AND writes its event in ONE
--                        transaction, so an order can never become paid by
--                        this route without the record of who did it.
--
-- The function runs as its caller (security invoker) and only the server's
-- service role may execute it; the route checks the caller is an admin, with
-- their own token, before it is called. Admins may read the events; nobody
-- in the browser may write, change or delete one. No existing table loses a
-- column or a row.
-- ============================================================

-- ------------------------------------------------------------
-- 1. The events
-- ------------------------------------------------------------
create table if not exists public.order_admin_events (
  id             uuid primary key default gen_random_uuid(),
  order_id       uuid not null references public.orders(id) on delete cascade,
  action         text not null check (action in ('cod_collected')),
  admin_user_id  uuid not null,
  admin_email    text,
  detail         jsonb not null default '{}'::jsonb,
  created_at     timestamptz not null default now()
);

create index if not exists order_admin_events_order_idx on public.order_admin_events (order_id, created_at);

alter table public.order_admin_events enable row level security;
drop policy if exists "order_admin_events admin read" on public.order_admin_events;
create policy "order_admin_events admin read"
  on public.order_admin_events for select
  using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));
revoke insert, update, delete, truncate on public.order_admin_events from anon, authenticated;

-- ------------------------------------------------------------
-- 2. mark_cod_collected — one transaction: paid, invoiced, recorded.
--
-- Returns the order's payment fields as they now stand, plus who collected,
-- or NULL when the guard matches nothing: not cash on delivery, already paid
-- (a second click, or another admin first) or cancelled. The invoice number
-- is generated by the server and used only if the order has none yet.
-- ------------------------------------------------------------
create or replace function public.mark_cod_collected(
  p_order_id       uuid,
  p_admin_user_id  uuid,
  p_admin_email    text,
  p_invoice_number text
)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v public.orders%rowtype;
begin
  if p_order_id is null or p_admin_user_id is null then
    raise exception 'order and admin are required' using errcode = '22023';
  end if;

  update public.orders
     set status = 'paid',
         payment_status = 'paid',
         paid_at = now(),
         invoice_number = coalesce(invoice_number, p_invoice_number),
         invoiced_at = coalesce(invoiced_at, now()),
         updated_at = now()
   where id = p_order_id
     and payment_method = 'cod'
     and (payment_status is null or payment_status <> 'paid')
     and fulfillment_status is distinct from 'cancelled'
  returning * into v;

  if not found then
    return null;
  end if;

  insert into public.order_admin_events (order_id, action, admin_user_id, admin_email)
    values (v.id, 'cod_collected', p_admin_user_id, nullif(btrim(p_admin_email), ''));

  return jsonb_build_object(
    'id', v.id,
    'order_number', v.order_number,
    'status', v.status,
    'payment_status', v.payment_status,
    'paid_at', v.paid_at,
    'invoice_number', v.invoice_number,
    'invoiced_at', v.invoiced_at,
    'collected_by', nullif(btrim(p_admin_email), '')
  );
end $$;

revoke all on function public.mark_cod_collected(uuid, uuid, text, text) from public, anon, authenticated;
grant execute on function public.mark_cod_collected(uuid, uuid, text, text) to service_role;

notify pgrst, 'reload schema';

-- ------------------------------------------------------------
-- Verify
-- ------------------------------------------------------------
select 'order_admin_events table, RLS on (expect 1)' as what, count(*)::text as detail
  from pg_class where relname = 'order_admin_events' and relrowsecurity
union all select 'mark_cod_collected (expect 1)', count(*)::text
  from pg_proc where proname = 'mark_cod_collected'
union all select 'running as its owner (expect 0)', count(*)::text
  from pg_proc where proname = 'mark_cod_collected' and prosecdef;
