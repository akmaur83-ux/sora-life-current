// ============================================================
// SORA LIFE — stylesheet bundler
//
//   node build/build-css.mjs        (rollup.config.mjs also calls buildCss())
//
// The storefront used to link 30 separate stylesheets from index.html. Every
// one of them is render-blocking, so on a mid-range Android over Slow 4G the
// browser opened 30 requests and could not paint until the last of them
// landed — and, because the assets are unhashed and served
// `max-age=0, must-revalidate`, a repeat visit re-validated all 30 again.
//
// It lives in build/ rather than scripts/ because .vercelignore excludes
// scripts/ from the deployment — a build step in there is not uploaded, and
// `npm run build` fails on Vercel while succeeding locally.
//
// This concatenates them, IN THE EXACT ORDER index.html declared them, into
// two files:
//
//   public/app.css           the storefront — one render-blocking request
//   public/app-deferred.css  admin / passport / creator, injected by
//                            src/main.jsx after first paint
//
// Order is the whole ballgame here: the architecture is cascade-ordered
// (v2-* deliberately loads last so it wins on equal specificity without
// !important), so STOREFRONT below must stay in its current sequence, and a
// new stylesheet must be appended in the position it would have occupied in
// index.html.
//
// Splitting the deferred four out moves them from the middle of the cascade
// to the end. That was verified safe rather than assumed: they share ZERO
// selectors with any storefront sheet that now loads before them, and they
// declare no bare element/:root rules, so nothing in the storefront can
// change. They are namespaced .adm / .ap-* / .psp / .ck-* / .crp / .crob.
//
// Every url() in these files is absolute (/public/...) or a data: URI, so
// concatenation cannot break a relative reference.
// ============================================================
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Storefront, in cascade order. This is the order index.html used.
const STOREFRONT = [
  'src/styles/tokens.css',
  'src/styles/base.css',
  'src/styles/components.css',
  'src/styles/layout.css',
  'src/styles/pages.css',
  'src/styles/pdp.css',
  'src/styles/home.css',
  'src/styles/promotions.css',
  'src/styles/v2-foundation.css',
  'src/styles/v2-header.css',
  'src/styles/v2-card.css',
  'src/styles/v2-home.css',
  'src/styles/v2-shop.css',
  'src/styles/v2-pdp.css',
  'src/styles/v2-cart-checkout.css',
  'src/styles/v2-mobile-cart.css',
  'src/styles/info.css',
  'src/styles/homepage-appearance.css',
  'src/styles/hero-cta.css',
  'src/styles/v2-home-marketplace.css',
  'src/styles/v2-home-discovery.css',
  'src/styles/category-spotlight.css',
  'src/styles/storefront-motion.css',
  'src/styles/storefront-background.css',
  'src/styles/storefront-refinements.css',
];

// Routes outside the shop: /admin, /passport, /creator. No customer browsing
// the storefront ever needs these bytes on the critical path.
const DEFERRED = [
  'src/admin/admin.css',
  'src/styles/passport.css',
  'src/styles/creator.css',
  'src/styles/creator-expressive.css',
];

function bundle(files, outFile, label) {
  const parts = files.map((rel) => {
    const css = readFileSync(resolve(ROOT, rel), 'utf8');
    return `/* ═══ ${rel} ═══ */\n${css.trim()}\n`;
  });
  const banner = `/* GENERATED by scripts/build-css.mjs — do not edit.\n`
    + `   Edit the sources listed below, then run: npm run build\n`
    + `   ${label}: ${files.length} stylesheets, in cascade order. */\n`;
  const out = banner + parts.join('\n');
  mkdirSync(resolve(ROOT, 'public'), { recursive: true });
  writeFileSync(resolve(ROOT, outFile), out);
  return out.length;
}

export function buildCss() {
  const a = bundle(STOREFRONT, 'public/app.css', 'storefront');
  const b = bundle(DEFERRED, 'public/app-deferred.css', 'admin / passport / creator');
  console.log(`  css: public/app.css          ${STOREFRONT.length} sheets, ${(a / 1024).toFixed(0)} KB raw`);
  console.log(`  css: public/app-deferred.css ${DEFERRED.length} sheets, ${(b / 1024).toFixed(0)} KB raw (not render-blocking)`);
  return { storefront: a, deferred: b };
}

// Runnable on its own for a CSS-only rebuild during design work.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) buildCss();
